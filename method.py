import re

# Окно: берём клиентов, пришедших не раньше внедрения ИИ. До августа бот
# в оформлении не работал, такие клиенты только занижают цифру.
AI_SINCE = "2026-08-01"

WEEK_DAYS = 7          # старое недельное окно; оставлено для сравнения

# --- кто есть ИИ -------------------------------------------------------------
AI_TYPES = ("arthur_ai", "bot", "ai")
AI_NAME = re.compile(
    r"артур\s*(ии|бот)"      # Артур ИИ
    r"|^\s*бот\s*$"          # Бот
    r"|геннадий",            # Геннадий — статуэтки и портреты
    re.I)

# --- кого не считаем совсем --------------------------------------------------
# Роповские учётки: через них руководители шлют рассылки, это не работа отдела.
# «Алина Роп книги», «ЗАРИНА РОП», «Рита ТОКАРЕВА Роповская учетка»,
# «ропская для старших мен» и любые другие с этим словом.
SKIP_NAME = re.compile(r"\bроп\w*\b", re.I)


def who(msg):
    """'client' | 'ai' | 'manager' | 'skip' — единственное место, где это решается."""
    stype = str(msg.get("sender_type") or "")
    name = str(msg.get("sender_name") or "").strip()
    if stype == "client":
        return "client"
    if SKIP_NAME.search(name):
        return "skip"
    if stype in AI_TYPES or AI_NAME.search(name):
        return "ai"
    return "manager"


def order_time(dlg, parse_dt):
    """Момент создания первого заказа — граница оформления. None, если заказа нет."""
    best = None
    for o in dlg.get("orders") or []:
        t = parse_dt(o.get("created_at") or "")
        if t and (best is None or t < best):
            best = t
    return best


def share(ai, man):
    tot = ai + man
    return ("%.0f%%" % (100.0 * ai / tot)) if tot else "—"
